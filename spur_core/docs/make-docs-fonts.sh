#!/bin/sh
# Makes docs/docs-fonts.css: whip's own font files (html/fonts/) embedded for docs.html.
#
# WHY EMBEDDED. docs.html is opened straight from disk as often as it is served, and a file:// page
# cannot load the font files beside it (the browser treats them as another origin). Embedded, the docs
# look the same from disk, from a server and with no internet.
#
# Run it from whip_core after a font in html/fonts changes:   sh docs/make-docs-fonts.sh
set -e
cd "$(dirname "$0")/.."
F=html/fonts
OUT=docs/docs-fonts.css
LATIN='U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
LATIN_EXT='U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF'

face() {   # family weight file range
    printf "@font-face { font-family: '%s'; font-style: normal; font-weight: %s; font-display: swap; src: url(data:font/woff2;base64,%s) format('woff2'); unicode-range: %s; }\n" \
        "$1" "$2" "$(base64 -w0 "$F/$3")" "$4"
}

{
    echo "/* GENERATED by docs/make-docs-fonts.sh from html/fonts — do not edit; run it again instead."
    echo "   Barlow for text, one file per weight docs.html uses (400-800); Bricolage Grotesque for titles,"
    echo "   one variable file (200-800). Every weight is real: no faux bold. */"
    for w in 400 500 600 700 800; do
        face 'Whip Barlow' "$w" "barlow-$w-latin.woff2" "$LATIN"
        face 'Whip Barlow' "$w" "barlow-$w-latin-ext.woff2" "$LATIN_EXT"
    done
    face 'Whip Bricolage' '200 800' bricolage-latin.woff2 "$LATIN"
    face 'Whip Bricolage' '200 800' bricolage-latin-ext.woff2 "$LATIN_EXT"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
