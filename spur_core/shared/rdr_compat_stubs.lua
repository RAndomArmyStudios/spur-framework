-- RedM (spur_core, 25 Nov 2026): RDR2 has no "is the engine running" native, and the stub's flat false made the
-- radial's Engine only ever turn it on (it toggles from this answer). The answer is now what this game last told
-- the vehicle through SetVehicleEngineOn: false for one it never told.
if not IsDuplicityVersion() then
    local told = {}   -- [vehicle] = boolean
    local setEngine = SetVehicleEngineOn
    function SetVehicleEngineOn(veh, on, ...)
        if veh and veh ~= 0 then
            told[veh] = (on == true or on == 1)
            local n = 0
            for v in pairs(told) do
                n = n + 1
                if n > 64 and not DoesEntityExist(v) then told[v] = nil end
            end
        end
        return setEngine(veh, on, ...)
    end
    function GetIsVehicleEngineRunning(veh)
        if veh == nil or told[veh] ~= true then return false end
        local there = DoesEntityExist(veh)   -- answers 1 here, and callers compare with `== true`
        return there == true or there == 1
    end
end
